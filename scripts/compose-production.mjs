// Derive a standalone production stack without modifying the vendored Supabase baseline.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { Document, parse, Scalar, visit } from 'yaml';

const compose = parse(readFileSync('docker-compose.yml', 'utf8'));
const upstream = 'infra/supabase/volumes/api/envoy';
const output = 'infra/production/envoy';
const clusters = parse(readFileSync(`${upstream}/cds.yaml`, 'utf8'));
const listeners = parse(readFileSync(`${upstream}/lds.template.yaml`, 'utf8'));
const backends = new Set(['auth', 'rest', 'storage']);

for (const name of ['studio', 'meta', 'realtime', 'functions', 'supavisor', 'dev-mail-relay']) {
  delete compose.services[name];
}

const gateway = compose.services['api-gw'];

gateway.depends_on = Object.fromEntries(
  [...backends].map((name) => [name, { condition: 'service_healthy' }]),
);
delete gateway.ports;
gateway.networks = ['default'];
gateway.volumes = gateway.volumes.map((mount) =>
  mount
    .replace(`${upstream}/cds.yaml`, `${output}/cds.yaml`)
    .replace(`${upstream}/lds.template.yaml`, `${output}/lds.template.yaml`),
);
delete compose.services.db.ports;
compose.services.db.networks = ['default'];

const usedVolumes = new Set();
const usedNetworks = new Set(['default']);

for (const service of Object.values(compose.services)) {
  for (const mount of service.volumes ?? []) {
    const source = typeof mount === 'string' ? mount.split(':')[0] : mount.source;

    if (Object.hasOwn(compose.volumes, source)) usedVolumes.add(source);
  }

  for (const name of Array.isArray(service.networks)
    ? service.networks
    : Object.keys(service.networks ?? {})) {
    usedNetworks.add(name);
  }
}

compose.volumes = Object.fromEntries(
  Object.entries(compose.volumes).filter(([name]) => usedVolumes.has(name)),
);
compose.networks = Object.fromEntries(
  Object.entries(compose.networks).filter(([name]) => usedNetworks.has(name)),
);
clusters.resources = clusters.resources.filter((cluster) => backends.has(cluster.name));

for (const listener of listeners.resources) {
  for (const chain of listener.filter_chains) {
    for (const filter of chain.filters) {
      const config = filter.typed_config;

      if (!config.route_config) continue;

      for (const host of config.route_config.virtual_hosts) {
        // Keep the original auth, key translation and RBAC configuration on every retained route.
        const publicRoute = host.routes.find((route) => route.match.prefix === '/auth/v1/verify');

        if (!publicRoute) throw new Error('Expected upstream public auth route was not found.');
        host.routes = host.routes.filter((route) => backends.has(route.route?.cluster));
        host.routes.push({
          match: { prefix: '/' },
          direct_response: { status: 404 },
          typed_per_filter_config: structuredClone(publicRoute.typed_per_filter_config),
        });
      }
    }
  }
}

const files = new Map([
  ['docker-compose.prod.yml', compose],
  [`${output}/cds.yaml`, clusters],
  [`${output}/lds.template.yaml`, listeners],
]);
const options = await resolveConfig('docker-compose.prod.yml');

for (const [file, document] of files) {
  const outputDocument = new Document(document);

  // Envoy's shell entrypoint substitutes optional empty keys after YAML generation.
  // Preserve quoted scalar values so substitution yields an empty string, never YAML null.
  visit(outputDocument, {
    Scalar(_key, node) {
      if (typeof node.value === 'string' && /^\$\{[A-Z0-9_]+\}$/.test(node.value))
        node.type = Scalar.QUOTE_DOUBLE;
    },
  });

  const content = await format(
    '# Generated by node scripts/compose-production.mjs; do not edit by hand.\n' +
      outputDocument.toString({ lineWidth: 120 }),
    { ...options, parser: 'yaml' },
  );

  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== content)
      throw new Error(
        `Production configuration is stale: ${file}. Run node scripts/compose-production.mjs.`,
      );
  } else {
    mkdirSync(file.includes('/') ? file.slice(0, file.lastIndexOf('/')) : '.', { recursive: true });
    writeFileSync(file, content);
  }
}

console.log(
  `Production Compose ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${Object.keys(compose.services).length} services; core API security and persistent storage preserved.`,
);
