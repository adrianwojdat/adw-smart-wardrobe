export function identifyPackingKey(name: string): PackingKey | undefined {
  const text = name.toLowerCase();

  // Specific types first: a spare shoe must not become a primary walking shoe.
  return packingKeys.find((key) => new RegExp(packingCatalog[key].pattern, 'iu').test(text));
}

export function packingGarmentMatches(key: PackingKey, name: string, subcategory: string) {
  const text = (subcategory + ' ' + name).toLowerCase();

  if (key === 'spare_shoes')
    return (
      /shoe|boot|sneaker|trainer|but|obuw|półbut/i.test(text) && !/flip.flop|klapk/i.test(text)
    );

  return new RegExp(packingCatalog[key].pattern, 'iu').test(text);
}
